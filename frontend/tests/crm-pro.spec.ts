  await dialog.getByRole('combobox', { name:/^Client/ }).selectOption({ label:name });
  await dialog.getByLabel('Description', { exact:true }).fill('Prestation de conseil');
  await dialog.getByLabel('Qté', { exact:true }).fill('3');
  await dialog.getByLabel('Prix HT (€)', { exact:true }).fill('19.99');
  await dialog.getByLabel('TVA (%)', { exact:true }).fill('20');
  await dialog.getByRole('button', { name:'Enregistrer', exact:true }).click();
  await expect(dialog).not.toBeVisible();
  const invoiceRow = page.getByRole('row').filter({ hasText:name });
  await expect(invoiceRow).toContainText('71,96');
  await invoiceRow.getByRole('button').first().click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name:/^Statut/ }).selectOption('issued');
  await dialog.getByRole('button', { name:'Enregistrer', exact:true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(invoiceRow).toContainText('Émise');
  await invoiceRow.getByRole('button').first().click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Prix HT (€)', { exact:true })).toBeDisabled();
  await dialog.getByRole('combobox', { name:/^Statut/ }).selectOption('paid');
  await dialog.getByLabel('Notes', { exact:true }).fill('Règlement confirmé pendant validation locale.');
  await dialog.getByRole('button', { name:'Enregistrer', exact:true }).click();

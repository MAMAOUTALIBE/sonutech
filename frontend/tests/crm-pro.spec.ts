  await dialog.getByLabel(/^Nom du projet/).fill(`Réalisation ${suffix}`);
  await dialog.getByRole('combobox', { name:/^Client/ }).selectOption({ label:name });
  await dialog.getByLabel('Budget (€)', { exact:true }).fill('1200.50');
  await dialog.getByRole('button', { name:'Enregistrer', exact:true }).click();
  await expect(dialog).not.toBeVisible();
  await menu.getByRole('link', { name:'Devis & Factures', exact:true }).click();
  await page.getByRole('button', { name:'Factures', exact:true }).click();
  await page.getByRole('button', { name:/Ajouter (un|une) facture/ }).click();
